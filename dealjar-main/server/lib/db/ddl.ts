// Idempotent DDL mirroring schema.ts. Plain statements, so the same bootstrap works on PGlite (local) and on
// Supabase or any other Postgres (production) without a CLI step.
export const DDL: string[] = [
  `CREATE TABLE IF NOT EXISTS users (
    id text PRIMARY KEY,
    address text NOT NULL UNIQUE,
    display_name text NOT NULL,
    role text NOT NULL DEFAULT 'member',
    username text,
    username_changed_at timestamptz,
    avatar_key text,
    banner_key text,
    bio text NOT NULL DEFAULT '',
    links text NOT NULL DEFAULT '[]',
    accent text NOT NULL DEFAULT '',
    currency text NOT NULL DEFAULT 'USD',
    goal_name text NOT NULL DEFAULT 'My first goal',
    goal_target bigint NOT NULL DEFAULT 100000000,
    referral_code text UNIQUE,
    referred_by text,
    show_stats boolean NOT NULL DEFAULT true,
    suspended boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (lower(username))`,
  `CREATE TABLE IF NOT EXISTS sponsors (
    id text PRIMARY KEY,
    user_id text NOT NULL UNIQUE,
    handle text NOT NULL UNIQUE,
    name text NOT NULL,
    tagline text NOT NULL DEFAULT '',
    bio text NOT NULL DEFAULT '',
    payout_address text NOT NULL,
    verified boolean NOT NULL DEFAULT false,
    status text NOT NULL DEFAULT 'pending',
    avatar_key text,
    banner_key text,
    links text NOT NULL DEFAULT '[]',
    demo boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS pools (
    id text PRIMARY KEY,
    sponsor_id text NOT NULL UNIQUE,
    funded bigint NOT NULL DEFAULT 0,
    committed bigint NOT NULL DEFAULT 0,
    paid bigint NOT NULL DEFAULT 0,
    per_person_cap bigint NOT NULL DEFAULT 10000000,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pools_sound CHECK (funded >= 0 AND committed >= 0 AND paid >= 0 AND committed + paid <= funded)
  )`,
  `CREATE TABLE IF NOT EXISTS pool_ledger (
    id text PRIMARY KEY,
    pool_id text NOT NULL,
    kind text NOT NULL,
    amount bigint NOT NULL,
    note text NOT NULL DEFAULT '',
    ref_id text,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX IF NOT EXISTS pool_ledger_pool ON pool_ledger (pool_id, created_at DESC)`,
  `CREATE TABLE IF NOT EXISTS deals (
    id text PRIMARY KEY,
    sponsor_id text NOT NULL,
    pool_id text NOT NULL,
    title text NOT NULL,
    summary text NOT NULL DEFAULT '',
    category text NOT NULL DEFAULT 'Groceries',
    price_luna bigint NOT NULL,
    reward_bps integer NOT NULL DEFAULT 0,
    reward_max bigint NOT NULL DEFAULT 5000000,
    expires_at timestamptz NOT NULL,
    community boolean NOT NULL DEFAULT false,
    banner_key text,
    hue integer NOT NULL DEFAULT 160,
    status text NOT NULL DEFAULT 'live',
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX IF NOT EXISTS deals_sponsor ON deals (sponsor_id)`,
  `CREATE TABLE IF NOT EXISTS payment_intents (
    id text PRIMARY KEY,
    user_id text NOT NULL,
    kind text NOT NULL,
    sponsor_id text NOT NULL,
    deal_id text,
    amount_luna bigint NOT NULL,
    recipient text NOT NULL,
    memo text NOT NULL,
    status text NOT NULL DEFAULT 'pending',
    tx_hash text,
    fail_reason text,
    reward_micro bigint NOT NULL DEFAULT 0,
    reward_state text NOT NULL DEFAULT 'none',
    nim_usd double precision,
    created_at timestamptz NOT NULL DEFAULT now(),
    confirmed_at timestamptz
  )`,
  `CREATE INDEX IF NOT EXISTS intents_user ON payment_intents (user_id, created_at DESC)`,
  `CREATE INDEX IF NOT EXISTS intents_status ON payment_intents (status, created_at)`,
  `CREATE TABLE IF NOT EXISTS jar_entries (
    id text PRIMARY KEY,
    user_id text NOT NULL,
    asset text NOT NULL,
    micro bigint NOT NULL,
    source text NOT NULL,
    label text NOT NULL,
    ref_id text,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX IF NOT EXISTS jar_user ON jar_entries (user_id, created_at DESC)`,
  `CREATE TABLE IF NOT EXISTS cashouts (
    id text PRIMARY KEY,
    user_id text NOT NULL,
    amount bigint NOT NULL,
    amount_luna bigint NOT NULL,
    address text NOT NULL,
    status text NOT NULL DEFAULT 'pending',
    tx_hash text,
    note text,
    created_at timestamptz NOT NULL DEFAULT now(),
    paid_at timestamptz
  )`,
  `CREATE TABLE IF NOT EXISTS referrals (
    id text PRIMARY KEY,
    referrer_id text NOT NULL,
    referee_id text NOT NULL UNIQUE,
    device_hash text NOT NULL,
    status text NOT NULL DEFAULT 'pending',
    reason text,
    reward bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    paid_at timestamptz
  )`,
  `CREATE INDEX IF NOT EXISTS referrals_device ON referrals (device_hash)`,
  `CREATE TABLE IF NOT EXISTS prices (
    key text PRIMARY KEY,
    value double precision NOT NULL,
    source text NOT NULL DEFAULT 'fallback',
    updated_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS reports (
    id text PRIMARY KEY,
    user_id text NOT NULL,
    deal_id text NOT NULL,
    reason text NOT NULL,
    status text NOT NULL DEFAULT 'open',
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS job_runs (
    id text PRIMARY KEY,
    name text NOT NULL,
    ok boolean NOT NULL,
    detail text NOT NULL DEFAULT '',
    ran_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS auth_challenges (
    nonce text PRIMARY KEY,
    message text NOT NULL,
    expires_at timestamptz NOT NULL,
    used boolean NOT NULL DEFAULT false
  )`,
];
